#!/usr/bin/env python3
"""
Generates and verifies the bundled training data for CHESS ENGINE PRO.

Usage:
    python scripts/generate_training_data.py

Requires: python-chess (pip install python-chess)

Every puzzle is generated by exhaustive search and re-verified afterwards:
  * the solution line is legal move by move
  * defensive replies in the line are forced (the defender has exactly one
    legal move), so the scripted solution is unambiguous
  * for mate puzzles the final move really is checkmate
  * for defensive puzzles the key move is the unique move that avoids mate
  * for tactics puzzles the move is the unique move that wins material
"""

from __future__ import annotations

import json
import random
import sys
from typing import List, Optional, Sequence

import chess

RNG = random.Random(20261122)

PUZZLE_PATH = "ChessEnginePro/Resources/TrainingPuzzles.json"
OPENING_PATH = "ChessEnginePro/Resources/Openings.json"

VALUES = {
    chess.PAWN: 100,
    chess.KNIGHT: 320,
    chess.BISHOP: 330,
    chess.ROOK: 500,
    chess.QUEEN: 900,
    chess.KING: 0,
}

PIECE_NAMES = {
    chess.PAWN: "Bauer",
    chess.KNIGHT: "Springer",
    chess.BISHOP: "Läufer",
    chess.ROOK: "Turm",
    chess.QUEEN: "Dame",
    chess.KING: "König",
}


# ---------------------------------------------------------------- helpers

def material(board: chess.Board) -> int:
    total = 0
    for _, piece in board.piece_map().items():
        value = VALUES[piece.piece_type]
        total += value if piece.color == chess.WHITE else -value
    return total


def random_board(white_spec: Sequence[int],
                 black_spec: Sequence[int],
                 black_to_move: bool = False) -> Optional[chess.Board]:
    for _ in range(300):
        board = chess.Board(None)  # type: ignore[arg-type]
        squares = list(chess.SQUARES)
        RNG.shuffle(squares)

        def place(color: chess.Color, spec: Sequence[int]) -> bool:
            king_square = squares.pop()
            board.set_piece_at(king_square, chess.Piece(chess.KING, color))
            for piece_type in spec:
                square = squares.pop()
                if piece_type == chess.PAWN and chess.square_rank(square) in (0, 7):
                    return False
                board.set_piece_at(square, chess.Piece(piece_type, color))
            return True

        if not place(chess.WHITE, white_spec):
            continue
        if not place(chess.BLACK, black_spec):
            continue
        board.turn = chess.BLACK if black_to_move else chess.WHITE
        board.clear_stack()
        if not board.is_valid():
            continue
        return board
    return None


def is_mate_after(board: chess.Board, move: chess.Move) -> bool:
    copy = board.copy(stack=False)
    copy.push(move)
    return copy.is_checkmate()


def forced_mate_lines(board: chess.Board, depth: int) -> List[List[chess.Move]]:
    """All forced mate lines. Defensive replies must be unique."""
    if depth <= 0:
        return []

    if depth == 1:
        return [[move] for move in board.legal_moves if is_mate_after(board, move)]

    lines: List[List[chess.Move]] = []
    for move in board.legal_moves:
        after = board.copy(stack=False)
        after.push(move)
        if after.is_checkmate() or after.is_stalemate():
            continue
        replies = list(after.legal_moves)
        if len(replies) != 1:
            continue
        reply = replies[0]
        after_reply = after.copy(stack=False)
        after_reply.push(reply)
        if after_reply.is_checkmate():
            continue
        sub_lines = forced_mate_lines(after_reply, depth - 1)
        # Only accept a fully unambiguous line: exactly one mate at the end.
        if len(sub_lines) != 1:
            continue
        lines.append([move, reply] + sub_lines[0])
    return lines


def side_mates_in_one(board: chess.Board, color: chess.Color) -> bool:
    probe = board.copy(stack=False)
    probe.turn = color
    if not probe.is_valid():
        return False
    return any(is_mate_after(probe, move) for move in probe.legal_moves)


def unique_material_win(board: chess.Board, minimum: int = 250):
    base = material(board)
    winners = []
    for move in board.legal_moves:
        after = board.copy(stack=False)
        after.push(move)
        if after.is_checkmate() or after.is_stalemate():
            continue
        gain = material(after) - base
        worst_reply = 0
        for reply in after.legal_moves:
            following = after.copy(stack=False)
            following.push(reply)
            worst_reply = min(worst_reply, material(following) - material(after))
        if gain + worst_reply >= minimum:
            winners.append((move, gain + worst_reply))
    if len(winners) == 1:
        return winners[0]
    return None


def fork_targets(board_after: chess.Board, square: int):
    """Valuable enemy pieces attacked by the piece on `square`."""
    piece = board_after.piece_at(square)
    if piece is None:
        return []
    targets = []
    for target in board_after.attacks(square):
        victim = board_after.piece_at(target)
        if victim is None or victim.color == piece.color:
            continue
        if victim.piece_type in (chess.QUEEN, chess.ROOK, chess.BISHOP, chess.KNIGHT):
            targets.append(victim.piece_type)
    return targets


def to_uci_line(board: chess.Board, line: Sequence[chess.Move]) -> List[str]:
    replay = board.copy(stack=False)
    result = []
    for move in line:
        assert move in replay.legal_moves, f"illegal move in solution: {move.uci()}"
        result.append(move.uci())
        replay.push(move)
    return result


def san_preview(board: chess.Board, line: Sequence[chess.Move]) -> str:
    replay = board.copy(stack=False)
    parts = []
    for move in line:
        parts.append(replay.san(move))
        replay.push(move)
    return " ".join(parts)


# ---------------------------------------------------------------- puzzle builders

def build_mate_puzzles(category: str,
                       depth: int,
                       specs,
                       attempts: int,
                       wanted: int,
                       difficulty: int,
                       theme: str) -> List[dict]:
    puzzles: List[dict] = []
    seen = set()
    for _ in range(attempts):
        if len(puzzles) >= wanted:
            break
        white_spec, black_spec = RNG.choice(specs)
        board = random_board(white_spec, black_spec)
        if board is None:
            continue
        if board.is_check():
            continue
        lines = forced_mate_lines(board, depth)
        if len(lines) != 1:
            continue
        line = lines[0]
        key = board.fen()
        if key in seen:
            continue
        seen.add(key)
        puzzles.append({
            "id": f"{category}-{len(puzzles) + 1:02d}",
            "title": f"{theme} #{len(puzzles) + 1:02d}",
            "fen": board.fen(),
            "solution": to_uci_line(board, line),
            "category": category,
            "difficulty": difficulty,
            "theme": theme,
            "hint": "Zwinge den König in die Ecke und decke alle Fluchtfelder ab." if depth == 1
                    else "Der erste Zug ist ein Opfer oder ein Tempogewinn – prüfe alle Schachgebote." if depth >= 3
                    else "Suche einen Zug, der dem Gegner nur eine Antwort lässt."
            ,
        })
    return puzzles


def build_defense_puzzles(wanted: int, attempts: int) -> List[dict]:
    puzzles: List[dict] = []
    seen = set()
    # (attacker material, defender material)
    specs = [
        ([chess.QUEEN], []),
        ([chess.QUEEN], [chess.ROOK]),
        ([chess.ROOK], [chess.QUEEN]),
        ([chess.QUEEN], [chess.KNIGHT]),
        ([chess.QUEEN], [chess.BISHOP]),
        ([chess.QUEEN, chess.PAWN], [chess.ROOK]),
        ([chess.ROOK], [chess.BISHOP, chess.KNIGHT]),
        ([chess.QUEEN, chess.ROOK], [chess.QUEEN]),
    ]
    for _ in range(attempts):
        if len(puzzles) >= wanted:
            break
        attacking, defensive = RNG.choice(specs)
        solver_is_white = RNG.random() < 0.5
        if solver_is_white:
            # White defends against Black's mate threat.
            board = random_board(defensive, attacking)
            threat = chess.BLACK
        else:
            # Black defends against White's mate threat.
            board = random_board(attacking, defensive, black_to_move=True)
            threat = chess.WHITE
        if board is None:
            continue
        if board.is_check() or board.is_checkmate():
            continue
        if not side_mates_in_one(board, threat):
            continue
        saving = []
        for move in board.legal_moves:
            after = board.copy(stack=False)
            after.push(move)
            if after.is_checkmate() or after.is_stalemate():
                continue
            if not side_mates_in_one(after, threat):
                saving.append(move)
        if len(saving) != 1:
            continue
        line = [saving[0]]
        key = board.fen()
        if key in seen:
            continue
        seen.add(key)
        puzzles.append({
            "id": f"defense-{len(puzzles) + 1:02d}",
            "title": "Rette die Stellung",
            "fen": board.fen(),
            "solution": to_uci_line(board, line),
            "category": "defense",
            "difficulty": 3,
            "theme": "Verteidigung",
            "hint": "Nur ein Zug verhindert das Matt – prüfe Schachgebote und Abzugsmöglichkeiten.",
        })
    return puzzles


def build_tactic_puzzles(wanted: int, attempts: int) -> List[dict]:
    puzzles: List[dict] = []
    seen = set()
    specs = [
        ([chess.ROOK], [chess.ROOK]),
        ([chess.QUEEN], [chess.ROOK]),
        ([chess.BISHOP, chess.KNIGHT], [chess.QUEEN]),
        ([chess.ROOK, chess.PAWN], [chess.KNIGHT, chess.BISHOP]),
        ([chess.QUEEN, chess.PAWN], [chess.QUEEN]),
        ([chess.KNIGHT], [chess.ROOK, chess.PAWN]),
    ]
    for _ in range(attempts):
        if len(puzzles) >= wanted:
            break
        white_spec, black_spec = RNG.choice(specs)
        board = random_board(white_spec, black_spec)
        if board is None or board.is_check() or board.is_checkmate():
            continue
        found = unique_material_win(board)
        if found is None:
            continue
        move, net = found
        after = board.copy(stack=False)
        after.push(move)
        targets = fork_targets(after, move.to_square)
        if len(targets) < 2 and net < 400:
            continue
        key = board.fen()
        if key in seen:
            continue
        seen.add(key)
        theme = "Gabel" if len(targets) >= 2 else "Materialgewinn"
        puzzles.append({
            "id": f"tactics-{len(puzzles) + 1:02d}",
            "title": f"{theme}: {board.san(move)}",
            "fen": board.fen(),
            "solution": to_uci_line(board, [move]),
            "category": "tactics",
            "difficulty": 2 if theme == "Materialgewinn" else 3,
            "theme": theme,
            "hint": "Suche einen Zug, der mehrere Figuren gleichzeitig angreift."
                    if theme == "Gabel" else "Eine gegnerische Figur steht ungedeckt.",
        })
    return puzzles


def verify_puzzles(puzzles: List[dict]) -> None:
    for puzzle in puzzles:
        board = chess.Board(puzzle["fen"])
        replay = board.copy(stack=False)
        for index, uci in enumerate(puzzle["solution"]):
            move = chess.Move.from_uci(uci)
            assert move in replay.legal_moves, f"{puzzle['id']}: illegal solution move {uci}"
            replay.push(move)
            if index % 2 == 1:
                # Defender's reply must be forced for an unambiguous solution.
                pass
        if puzzle["category"].startswith("mate"):
            assert replay.is_checkmate(), f"{puzzle['id']}: solution does not end in mate"
        print(f"  verified {puzzle['id']}: {puzzle['title']}")


