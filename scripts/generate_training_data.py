def build_openings() -> List[dict]:
    result = []
    for name, eco, description, moves in OPENINGS:
        board = chess.Board()
        for san in moves:
            try:
                move = board.parse_san(san)
            except ValueError as error:
                raise SystemExit(f"Ungültiger Zug in '{name}': {san} ({error})")
            board.push(move)
        result.append({
            "id": name.lower().replace(" ", "-").replace("(", "").replace(")", "").replace("ß", "ss"),
            "name": name,
            "eco": eco,
            "description": description,
            "moves": list(moves),
        })
    return result


# ---------------------------------------------------------------- main

def main() -> int:
    print("Erzeuge Matt-Aufgaben …")
    puzzles: List[dict] = []

    mate1 = build_mate_puzzles(
        "mate1", 1,
        [([chess.QUEEN], []), ([chess.ROOK], []), ([chess.QUEEN, chess.ROOK], [])],
        attempts=4000, wanted=12, difficulty=1, theme="Matt in 1")
    puzzles += mate1
    print(f"  {len(mate1)} Matt-in-1-Aufgaben")

    mate2 = build_mate_puzzles(
        "mate2", 2,
        [([chess.QUEEN], []), ([chess.ROOK], []), ([chess.QUEEN, chess.ROOK], [])],
        attempts=1200, wanted=10, difficulty=2, theme="Matt in 2")
    puzzles += mate2
    print(f"  {len(mate2)} Matt-in-2-Aufgaben")

    mate3 = build_mate_puzzles(
        "mate3", 3,
        [([chess.QUEEN], []), ([chess.ROOK], []), ([chess.QUEEN, chess.ROOK], [])],
        attempts=500, wanted=8, difficulty=4, theme="Matt in 3")
    puzzles += mate3
    print(f"  {len(mate3)} Matt-in-3-Aufgaben")

    print("Erzeuge Endspiel-Aufgaben …")
    endgame = build_mate_puzzles(
        "endgame", 3,
        [([chess.ROOK], []), ([chess.QUEEN], []), ([chess.ROOK, chess.KNIGHT], [])],
        attempts=1200, wanted=8, difficulty=3, theme="Endspiel-Technik")
    puzzles += endgame
    print(f"  {len(endgame)} Endspiel-Aufgaben")

    print("Erzeuge Taktik-Aufgaben …")
    tactics = build_tactic_puzzles(wanted=10, attempts=6000)
    puzzles += tactics
    print(f"  {len(tactics)} Taktik-Aufgaben")

    print("Erzeuge Verteidigungs-Aufgaben …")
    defense = build_defense_puzzles(wanted=10, attempts=60000)
    puzzles += defense
    print(f"  {len(defense)} Verteidigungs-Aufgaben")

    print("Verifiziere alle Lösungen …")
    verify_puzzles(puzzles)

    with open(PUZZLE_PATH, "w", encoding="utf-8") as handle:
        json.dump(puzzles, handle, ensure_ascii=False, indent=2)
        handle.write("\n")

    openings = build_openings()
    with open(OPENING_PATH, "w", encoding="utf-8") as handle:
        json.dump(openings, handle, ensure_ascii=False, indent=2)
        handle.write("\n")

    print(f"\n{len(puzzles)} Aufgaben und {len(openings)} Eröffnungen geschrieben.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
